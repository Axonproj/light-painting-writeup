#!/usr/bin/env python3
#
# ed_cal.py — an energy-density step wedge for the light pen, in one colour.
# Writes ed_cal.plot (or --out).
#
# Energy density (ED) is the light a line gets per millimetre: brightness /
# speed, in brightness per 1000 mm/min. With dynamic brightness on it is the
# same all along a stroke, so one row drawn at one ED shows what that ED looks
# like, and a frame of rows shows the range to choose from.
#
# Each row, lowest ED at the bottom, is a 240 mm line: the single stroke, and
# whether it is even end to end. The plotter draws nothing else. Each row's ED
# is lettered on the picture afterwards, from the `#@` lines written here
# (annotate.py; paint runs it).
#
# Every row is drawn at the same 25000 mm/min, the fastest there is, so each
# ED gets the highest LED value it can have; the ED is set by the value in the
# colour. The LED only has whole values, so the EDs asked for are moved to the
# nearest ones it can give, and those are what the labels say.
#
#   ./ed_cal.py --colour "0 255 0" --out ed_cal_green.plot
#   ./ed_cal.py --colour "0 0 255" --from 0.1 --to 1.6 --steps 6
#
# The most there is at 25000 mm/min is ED 4.0, the LED full on.
#
# The level is in the colour itself: shoot at 100%,
#   ./paint ed_cal_green.plot 100 -raw -tv=S

import argparse
import outdirs as OD

BED = (393.0, 262.0)      # mm
MARGIN_MM = 10.0          # keep the figure clear of the limits
FEED = 25000              # mm/min
ED_PER_VALUE = 100.0 / 255 / (FEED / 1000.0)   # ED of LED value 1 at FEED

ROW_FIRST_Y = 22.0        # centre of the bottom row
ROW_STEP_MAX = 30.0       # rows no further apart than this
ED_MAX = 255 * ED_PER_VALUE
LABEL_X, LABEL_H = 12.0, 7.0
LINE_X = (56.0, 296.0)


def wedge_values(ed_from, ed_to, steps):
    """LED values for `steps` EDs spaced by a constant ratio, duplicates dropped."""
    if steps < 2:
        eds = [ed_from]
    else:
        ratio = (ed_to / ed_from) ** (1.0 / (steps - 1))
        eds = [ed_from * ratio ** i for i in range(steps)]
    values = []
    for ed in eds:
        v = min(255, max(1, round(ed / ED_PER_VALUE)))
        if v not in values:
            values.append(v)
    return values


def scaled(colour, value):
    """The colour with its strongest channel at `value`."""
    top = max(colour)
    return tuple(round(c * value / top) for c in colour)


def main():
    global FEED, ED_PER_VALUE, ED_MAX
    ap = argparse.ArgumentParser(description="Energy-density step wedge in one colour.")
    ap.add_argument("--colour", default="0 255 0", help='"R G B", the colour at full drive')
    ap.add_argument("--from", dest="ed_from", type=float, default=0.06, help="lowest ED")
    ap.add_argument("--to", dest="ed_to", type=float, default=None,
                    help="highest ED (default and most: the LED full on, %.1f at %d mm/min)" % (ED_MAX, FEED))
    ap.add_argument("--speed", type=int, default=FEED,
                    help="mm/min for every row (default %d, the fastest). Slower reaches higher EDs: "
                         "match the plot being calibrated (rings3d runs at 3000)" % FEED)
    ap.add_argument("--steps", type=int, default=16, help="rows asked for")
    ap.add_argument("--out", default=OD.plot("ed_cal.plot"))
    ap.add_argument("--led", default="",
                    help='the LED and its filters, for the caption ("APA-106 8 mm, 4-stop ND"): '
                         'EDs differ from one part to another')
    a = ap.parse_args()
    FEED = a.speed
    ED_PER_VALUE = 100.0 / 255 / (FEED / 1000.0)
    ED_MAX = 255 * ED_PER_VALUE
    if a.ed_to is None:
        a.ed_to = ED_MAX

    colour = tuple(int(v) for v in a.colour.split())
    if len(colour) != 3 or max(colour) <= 0:
        raise SystemExit('--colour is "R G B" with something lit')
    if not 0 < a.ed_from <= a.ed_to:
        raise SystemExit("--from must be above 0 and no more than --to")
    if a.ed_to > ED_MAX + 1e-9:
        raise SystemExit("--to: the most at %d mm/min is ED %.1f, the LED full on" % (FEED, ED_MAX))
    values = wedge_values(a.ed_from, a.ed_to, a.steps)
    step = ROW_STEP_MAX
    if len(values) > 1:
        step = min(step, int((BED[1] - 2 * ROW_FIRST_Y) / (len(values) - 1) * 2) / 2)   # whole half mm
    if step < LABEL_H + 4:
        raise SystemExit("too many rows for the bed: reduce --steps")

    out = [
        "# %s — generated by ed_cal.py, do not edit." % a.out,
        "# Energy-density step wedge, colour %d %d %d, at %d mm/min." % (colour + (FEED,)),
        "# Each row is a 240 mm line. ED = LED value x %.5f." % ED_PER_VALUE,
        "# The #@ lines letter the picture afterwards (annotate.py).",
    ]
    rows = [(ROW_FIRST_Y + i * step, v) for i, v in enumerate(values)]
    out += ["#   y = %-5g LED value %-3d ED %.3f" % (y, v, v * ED_PER_VALUE) for y, v in rows]
    out += [
        "# The level is in the colour itself: shoot at 100%.",
        "# Dynamic brightness on. UNPLUG THE SOLENOID (see `help`).",
        "",
        "home",
        "status          # check WPos:393.000,0.000 before plotting",
        "",
        "lightpen on",
        "speed %d" % FEED,
        "dynamic on",
    ]
    last = None
    for y, v in rows:
        ed = v * ED_PER_VALUE
        out += ["", "# ED %.3f" % ed]
        out.append('#@ text %g %g %g "%.3f"' % (LABEL_X, y - LABEL_H / 2, LABEL_H, ed))
        row = scaled(colour, v)
        if row != last:
            out.append("colour %d %d %d" % row)
            last = row
        if not MARGIN_MM <= y <= BED[1] - MARGIN_MM:
            raise SystemExit("wedge leaves the bed at y = %.1f" % y)
        out.append("moveto %.2f %.2f" % (LINE_X[0], y))
        out.append("drawto %.2f %.2f" % (LINE_X[1], y))
    led = (", " + a.led.replace('"', "'")) if a.led else ""
    out += ["", "#@ text %g %g 4 \"ED wedge, colour %d %d %d, %d mm/min%s    {shot}    {exposure}    {camera}\""
            % ((LABEL_X, 5.0) + colour + (FEED, led)),
            "", "dynamic off", "penup", "colour off",
            "home            # park at the home corner when done", ""]
    with open(a.out, "w") as f:
        f.write("\n".join(out))
    print("%s: %d rows" % (a.out, len(rows)))
    for y, v in rows:
        print("  y = %-5g LED value %-3d ED %.3f" % (y, v, v * ED_PER_VALUE))


main()
