#!/usr/bin/env python3
#
# hue_ed.py — a chart of hue against energy density, to see in advance what
# a colour at a given level will look like on the camera.
#
# One row per hue: the colour wheel in --hue-step degrees at full saturation,
# then grey (the SK6812's white element), then any --colours given (the wave
# palette by default). Along each row, dashes at rising energy density (ED,
# brightness / speed in brightness per 1000 mm/min), ratio-spaced from --from
# to --to: what a stretch of line at that level looks like.
#
# Drawn as tree_anim.py's frames are: at --speed, dynamic brightness on, and
# shot at brightness 100 so the LED value is the colour value itself, rounded
# to whole steps as any plot is (the low EDs show how coarse they are). Each
# dash is its own stroke, so its colour is set during the air move before it.
#
# Labels (hue, colour, ED) go on the finished picture from `#@` lines.
#
#   ./hue_ed.py                         # writes hue_ed.plot
#   ./paint hue_ed.plot 100 -raw -nocal -tv=S
#
# ED for a tree_anim frame: brightness x colour/255 / speed x 1000; the
# waves at brightness 15, 4500 mm/min and full colour are ED 3.3, the body
# (level 0.28) about 0.9, far branches (x0.45) about 0.4.

import argparse
import colorsys
import outdirs as OD

BED = (393.0, 262.0)
X0, X1 = 52.0, 383.0          # the dashes
GAP = 4.0                     # between dashes
Y_TOP, Y_BOTTOM = 246.0, 10.0
LABEL_X = 6.0

WAVE_DEFAULT = "255 40 160;255 170 0;0 255 120;0 200 255;40 60 255"


def main():
    ap = argparse.ArgumentParser(description="Hue against energy density chart for the light pen.")
    ap.add_argument("--speed", type=int, default=4500, help="mm/min, as the frames are drawn")
    ap.add_argument("--from", dest="ed_from", type=float, default=0.25)
    ap.add_argument("--to", dest="ed_to", type=float, default=6.0)
    ap.add_argument("--steps", type=int, default=8)
    ap.add_argument("--hue-step", type=float, default=15.0, help="degrees between hue rows")
    ap.add_argument("--colours", default=WAVE_DEFAULT, help='extra rows, "R G B;R G B;..." (the wave palette by default)')
    ap.add_argument("--out", default=OD.plot("hue_ed.plot"))
    ap.add_argument("--bidir", action="store_true",
                    help="draw every other dash right to left (a radio delay shifts the two ways apart, the mechanics do not)")
    ap.add_argument("--label-dy", type=float, default=0.0,
                    help="move the labels by this many mm (the -nocal map put the rows ~4.7 mm low, 2026-11-04)")
    a = ap.parse_args()

    ed_max = 100.0 / (a.speed / 1000.0)               # LED full on at this speed
    if a.ed_to > ed_max:
        raise SystemExit("hue_ed: ED %.2f is the most at %d mm/min" % (ed_max, a.speed))
    ratio = (a.ed_to / a.ed_from) ** (1.0 / (a.steps - 1))
    eds = [a.ed_from * ratio ** i for i in range(a.steps)]
    per_value = ed_max / 255.0                        # ED of one LED step

    rows = []
    h = 0.0
    while h < 360 - 1e-6:
        r, g, b = colorsys.hsv_to_rgb(h / 360.0, 1, 1)
        rows.append(("hue %.0f" % h, (r, g, b)))
        h += a.hue_step
    rows.append(("grey", (1.0, 1.0, 1.0)))
    for c in filter(None, (s.strip() for s in a.colours.split(";"))):
        v = [float(t) for t in c.split()]
        top = max(v)
        rows.append(("%d %d %d" % tuple(v), tuple(x / top for x in v)))

    pitch = (Y_TOP - Y_BOTTOM) / (len(rows) - 1)
    dash = (X1 - X0 - GAP * (a.steps - 1)) / a.steps
    L = ["# %s — generated by hue_ed.py, do not edit." % a.out,
         "# Hue against energy density: %d rows, ED %.2f to %.2f in %d steps, at %d mm/min."
         % (len(rows), a.ed_from, a.ed_to, a.steps, a.speed),
         "# Shoot at brightness 100: ./paint %s 100 -raw -nocal" % a.out,
         "# Dynamic brightness on. UNPLUG THE SOLENOID (see `help`).", "",
         "lightpen on", "speed %d" % a.speed, "dynamic on", ""]
    notes = ["#@ colour 210 210 210"]
    drawn = 0.0
    for n, (label, rgb) in enumerate(rows):
        y = Y_TOP - n * pitch
        notes.append('#@ text %.1f %.1f 4 "%s"' % (LABEL_X, y - 1.6 + a.label_dy, label))
        L.append("# row %s" % label)
        for k, ed in enumerate(eds):
            value = ed / per_value                     # LED value of the strongest channel
            c = tuple(int(round(value * x)) for x in rgb)
            if max(c) == 0:
                continue
            x0 = X0 + k * (dash + GAP)
            xa, xb = (x0 + dash, x0) if a.bidir and k % 2 else (x0, x0 + dash)
            L += ["colour %d %d %d" % c, "moveto %.2f %.2f" % (xa, y), "drawto %.2f %.2f" % (xb, y)]
            drawn += dash
    for k, ed in enumerate(eds):
        x0 = X0 + k * (dash + GAP)
        # the ED, and the whole LED steps it really gets at full colour
        v = max(1, round(ed / per_value))
        notes.append('#@ text %.1f %.1f 4 "ED %.2g"' % (x0, Y_TOP + 10 + a.label_dy, ed))
        notes.append('#@ text %.1f %.1f 3 "LED %d of 255"' % (x0, Y_TOP + 5 + a.label_dy, v))
    L += ["", "dynamic off", "penup", "colour off", "home", ""] + notes + [""]
    open(a.out, "w").write("\n".join(L))
    secs = drawn / (a.speed / 60.0) + len(rows) * a.steps * 0.35
    print("%s: %d rows x %d EDs, %.0f mm drawn, about %.0f s" % (a.out, len(rows), a.steps, drawn, secs))


main()
