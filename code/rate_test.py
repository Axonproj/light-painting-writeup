#!/usr/bin/env python3
#
# rate_test.py — generate rate_test.plot: how fast can the LED change colour?
#
# Horizontal lines of alternating red and green stripes, the stripes getting
# shorter from one pair of lines to the next, so the colour changes faster and
# faster down the frame. Where the stripes stop being clean and evenly spaced,
# the bridge / carrier link has run out of speed. A stall in the motion (the
# feed not keeping up) shows as a bright blob.
#
#   * Every stripe length is drawn twice, left to right and then right to left,
#     with red and green in the SAME places on both. A colour that arrives late
#     shifts the pattern along the direction of travel, so the two lines of a
#     pair shift opposite ways: the offset between them is twice the lag.
#   * The stripes fill the test zone, x = ZONE[0]..ZONE[1]. Each line runs up to
#     speed and slows down again with the LED dark, outside it, so inside the
#     zone the pen is at constant speed and every stripe lasts the same time.
#   * Two blue rails stand RAIL_GAP mm clear of the zone's ends: the first
#     stripe starts exactly that far from a rail.
#   * The light changes about 6.5 ms after the pen passes the point where the
#     colour was commanded (measured with --lag 0: pairs 5-6 mm apart at
#     417 mm/s). So every colour command is moved upstream, against the
#     direction of travel, by --lag ms of travel at that line's feed, to put
#     the borders where they were meant to be and the pairs in line.
#   * GRBL can only go as fast as it can stop within the moves it has queued,
#     so short stripes force a lower feed (see feed_for). The stripe colours
#     are dimmed in proportion, to keep the exposure the same on every line.
#
# Usage:
#   ./rate_test.py                 # writes rate_test.plot, prints the key
#   ./rate_test.py --stripes 20,10,5,2.5
#   ./rate_test.py --lag 0         # no compensation: shows the raw lag
# Shoot it with plotsnap, e.g. `plotsnap rate_test.plot 16 -lights`.

import argparse
import math
import sys
import outdirs as OD

BED_X, BED_Y = 393.0, 262.0
ACCEL = 800.0                   # mm/s^2, GRBL $120/$121
MAX_FEED = 25000.0              # mm/min, GRBL $110/$111
QUEUED = 12                     # moves GRBL can be counted on to have queued (buffer is 16)
ZONE = (117.0, 277.0)           # stripes: 160 mm, a whole number of every default stripe
RUN = 112.0                     # dark run-up / run-down: reaches MAX_FEED in 108.5 mm
RAIL_GAP = 10.0
PITCH = 10.0                    # mm between lines
TOP = 250.0                     # y of the first line


def feed_for(stripe):
    """Feed (mm/min) GRBL will hold through stripes this long: it must be able
    to stop within QUEUED of them. 0.85 keeps clear of the limit."""
    v = 0.85 * math.sqrt(2 * ACCEL * QUEUED * stripe)
    return min(MAX_FEED, round(v * 60 / 100) * 100)


def main():
    ap = argparse.ArgumentParser(description="Colour-change rate test plot.")
    ap.add_argument("--stripes", default="40,20,10,8,5,4,3.2,2.5,2,1.6,1.25,1",
                    help="stripe lengths, mm, longest first")
    ap.add_argument("--lag", type=float, default=6.5,
                    help="colour lag to compensate, ms (0 = none)")
    ap.add_argument("--out", default="rate_test")
    a = ap.parse_args()
    stripes = [float(v) for v in a.stripes.split(",")]
    width = ZONE[1] - ZONE[0]
    y_last = TOP - (2 * len(stripes) - 1) * PITCH
    if y_last < 5:
        sys.exit("%d stripe lengths need more height than the bed has" % len(stripes))

    key = []
    with open(OD.plot(a.out + ".plot"), "w") as f:
        f.write("# %s.plot — generated by %s. Do not edit.\n"
                % (a.out, " ".join(["rate_test.py"] + sys.argv[1:])))
        f.write("# Red/green stripes at a rising rate of colour change; see rate_test.py.\n")
        f.write("# Stripes fill x=%g..%g; blue rails %g mm clear of each end.\n"
                % (ZONE[0], ZONE[1], RAIL_GAP))
        f.write("# Colour commands lead their borders by %g ms of travel.\n" % a.lag)
        f.write("\nhome\nstatus          # check WPos:393.000,0.000 before plotting\n")
        f.write("\nlightpen on\n")
        f.write("\n# --- blue rails ---\ncolour 0 0 255\n")
        f.write("moveto %.3f %.3f\ndrawto %.3f %.3f\n"
                % (ZONE[0] - RAIL_GAP, TOP + 7, ZONE[0] - RAIL_GAP, y_last - 7))
        f.write("moveto %.3f %.3f\ndrawto %.3f %.3f\n"
                % (ZONE[1] + RAIL_GAP, y_last - 7, ZONE[1] + RAIL_GAP, TOP + 7))

        y = TOP
        for stripe in stripes:
            n = int(round(width / stripe))
            if abs(n * stripe - width) > 1e-6 or n % 2:
                sys.exit("stripe %g mm does not go into the %g mm zone an even number of times"
                         % (stripe, width))
            feed = feed_for(stripe)
            ms = stripe / (feed / 60.0) * 1000
            level = int(round(255 * feed / MAX_FEED))       # same exposure at every feed
            colours = [(level, 0, 0), (0, level, 0)]        # red first from the left
            lead = feed / 60.0 * a.lag / 1000               # mm the pen travels in the lag
            for l2r in (True, False):
                key.append("y %5.1f  %s  stripe %5.2f mm  feed %5d  %5.1f ms per colour (%3.0f /s)  lead %.2f mm"
                           % (y, "L->R" if l2r else "R->L", stripe, feed, ms, 1000 / ms, lead))
                f.write("\n# %s\nspeed %d\n" % (key[-1], feed))
                # Where the colour commands go: each border, moved upstream.
                edges = [ZONE[0] + k * stripe - (lead if l2r else -lead) for k in range(n + 1)]
                order = list(range(n)) if l2r else list(range(n - 1, -1, -1))
                x_from = ZONE[0] - RUN if l2r else ZONE[1] + RUN
                x_to = ZONE[1] + RUN if l2r else ZONE[0] - RUN
                f.write("colour 0 0 0\nmoveto %.3f %.3f\n" % (x_from, y))
                f.write("drawto %.3f %.3f\n" % (edges[0] if l2r else edges[n], y))
                for k in order:
                    f.write("colour %d %d %d\n" % colours[k % 2])
                    f.write("drawto %.3f %.3f\n" % (edges[k + 1] if l2r else edges[k], y))
                f.write("colour 0 0 0\ndrawto %.3f %.3f\n" % (x_to, y))
                y -= PITCH
        f.write("\npenup\ncolour off\nhome            # park at the home corner when done\n")

    print("%s.plot: %d lines" % (a.out, 2 * len(stripes)))
    print("\n".join(key))


if __name__ == "__main__":
    main()
