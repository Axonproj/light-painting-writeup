#!/usr/bin/env python3
#
# photo_hlines.py — sample a photo along horizontal lines and write the
# light-paint plot of those lines, with a preview.
#
# The photo is scaled to --width mm, and sampled along horizontal lines
# --pitch mm apart. Each line is cut into --seg mm pieces; a piece takes the
# mean colour of the photo over its own length and one pitch of height, so
# nothing between the lines is thrown away.
#
# Usage:
#   ./photo_hlines.py PHOTO                      # 350 mm wide, 6 mm pitch
#   ./photo_hlines.py PHOTO --pitch 4 --seg 10
#   ./photo_hlines.py PHOTO --crop 0,0.5,1,1     # bottom half of the photo only
# Writes NAME.plot and NAME_preview.png (--out NAME, default from the photo's
# name).
#
# The plot draws the lines top to bottom, alternating direction, changing
# colour mid-stroke. Its lower-left corner is at --origin (default: 5 mm in
# from xmin and ymax, away from the camera glow at the home corner). Colours
# are full range: set the exposure with paint's brightness.

import argparse
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter
import outdirs as OD

PX_PER_MM = 8                   # preview scale, as the paint pipeline's results
PLOT_X, PLOT_Y = 393.0, 262.0   # bed, mm
MARGIN = 5.0                    # mm of black round the preview


def sample(photo, width, pitch, seg):
    """Return (height_mm, [(y_mm, [(x0, x1, (r, g, b)), ...]), ...]), y up."""
    w_px, h_px = photo.size
    height = width * h_px / w_px
    n_lines = int(height // pitch) + 1
    n_segs = int(round(width / seg))
    y_first = (height - (n_lines - 1) * pitch) / 2      # centre the lines
    pix = np.asarray(photo.convert("RGB"), dtype=float)
    mm = w_px / width                                   # photo px per mm
    lines = []
    for i in range(n_lines):
        y = y_first + i * pitch                         # mm up from the bottom
        top = int(round((height - y - pitch / 2) * mm))
        bot = int(round((height - y + pitch / 2) * mm))
        top, bot = max(top, 0), min(bot, h_px)
        segs = []
        for k in range(n_segs):
            x0, x1 = k * width / n_segs, (k + 1) * width / n_segs
            box = pix[top:bot, int(round(x0 * mm)):int(round(x1 * mm))]
            rgb = tuple(int(round(v)) for v in box.reshape(-1, 3).mean(axis=0))
            segs.append((x0, x1, rgb))
        lines.append((y, segs))
    return height, lines


def preview(height, width, lines, stroke, path):
    s = PX_PER_MM
    W = int(round((width + 2 * MARGIN) * s))
    H = int(round((height + 2 * MARGIN) * s))
    img = Image.new("RGB", (W, H), "black")
    d = ImageDraw.Draw(img)
    for y, segs in lines:
        py = (MARGIN + height - y) * s
        for x0, x1, rgb in segs:
            d.line([((MARGIN + x0) * s, py), ((MARGIN + x1) * s, py)],
                   fill=rgb, width=max(1, int(round(stroke * s))))
    glow = img.filter(ImageFilter.GaussianBlur(stroke * s))     # LED bloom
    img = Image.fromarray(np.maximum(np.asarray(img), np.asarray(glow) // 2))
    img.save(path)


def write_plot(path, cmdline, height, width, lines, origin, speed):
    ox, oy = origin
    with open(path, "w") as f:
        f.write("# %s — generated by %s. Do not edit.\n" % (path, cmdline))
        f.write("# %g x %.1f mm at origin %g,%g; %d lines, %d colour steps per line.\n"
                % (width, height, ox, oy, len(lines), len(lines[0][1])))
        f.write("\nhome\nstatus          # check WPos:393.000,0.000 before plotting\n")
        f.write("\nlightpen on\nspeed %d\n" % speed)
        for n, (y, segs) in enumerate(reversed(lines)):
            if n % 2:                                   # every other line right to left
                segs = [(x1, x0, rgb) for x0, x1, rgb in reversed(segs)]
            f.write("\n# y=%.2f\n" % y)
            last = None
            for k, (x0, x1, rgb) in enumerate(segs):
                if rgb != last:
                    f.write("colour %d %d %d\n" % rgb)
                    last = rgb
                if k == 0:
                    f.write("moveto %.2f %.2f\n" % (ox + x0, oy + y))
                f.write("drawto %.2f %.2f\n" % (ox + x1, oy + y))
        f.write("\npenup\ncolour off\nhome            # park at the home corner when done\n")


def main():
    ap = argparse.ArgumentParser(description="Sample a photo along horizontal lines; preview the plot.")
    ap.add_argument("photo")
    ap.add_argument("--width", type=float, default=350.0, help="plot width, mm")
    ap.add_argument("--pitch", type=float, default=6.0, help="line spacing, mm")
    ap.add_argument("--seg", type=float, default=5.0, help="colour step along a line, mm")
    ap.add_argument("--stroke", type=float, default=1.5, help="preview stroke width, mm")
    ap.add_argument("--speed", type=int, default=3000, help="drawing feed, mm/min")
    ap.add_argument("--origin", help="lower-left corner X,Y in mm (default 5 in from xmin, ymax)")
    ap.add_argument("--crop", help="part of the photo to use: LEFT,TOP,RIGHT,BOTTOM "
                    "as fractions (0,0 = top left); --width is the width of that part")
    ap.add_argument("--out", help="output name (default: from the photo)")
    a = ap.parse_args()

    name = a.out or os.path.splitext(os.path.basename(a.photo))[0]
    photo = Image.open(a.photo)
    if a.crop:
        l, t, r, b = (float(v) for v in a.crop.split(","))
        photo = photo.crop((round(l * photo.width), round(t * photo.height),
                            round(r * photo.width), round(b * photo.height)))
    height, lines = sample(photo, a.width, a.pitch, a.seg)
    origin = (tuple(float(v) for v in a.origin.split(",")) if a.origin
              else (5.0, round(PLOT_Y - 5.0 - height, 1)))
    if (origin[0] < 0 or origin[1] < 0 or origin[0] + a.width > PLOT_X
            or origin[1] + height > PLOT_Y):
        sys.exit("plot does not fit the %g x %g mm bed at origin %g,%g"
                 % (PLOT_X, PLOT_Y, origin[0], origin[1]))
    cmdline = " ".join(["photo_hlines.py"] + sys.argv[1:])
    write_plot(OD.plot(name + ".plot"), cmdline, height, a.width, lines, origin, a.speed)
    out = OD.preview(name + "_preview.png")
    preview(height, a.width, lines, a.stroke, out)
    n_segs = len(lines[0][1])
    print("%s.plot: %.1f m of line at %d mm/min = %.1f min drawing; a colour step every %.0f ms"
          % (name, len(lines) * a.width / 1000, a.speed,
             len(lines) * a.width / a.speed, a.width / n_segs / a.speed * 60000))
    print("%s: %.0f x %.1f mm, %d lines at %g mm, %d colour steps of %g mm per line"
          % (out, a.width, height, len(lines), a.pitch, len(lines[0][1]),
             a.width / len(lines[0][1])))


if __name__ == "__main__":
    main()
