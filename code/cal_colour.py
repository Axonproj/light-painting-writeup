#!/usr/bin/env python3
#
# cal_colour.py — colour-coded calibration grid for the light-painting camera.
#
# Writes two things from ONE description of the pattern, so they cannot drift:
#   cal_colour.plot     what the plotter draws (plotter.pl `run cal_colour.plot`)
#   cal_colour_ref.png  the same pattern rendered in plot space — the "direct
#                       image" a photograph should align with after correction.
#
# Every line carries a hue from a repeating sequence of six, so each grid
# intersection identifies itself from the colours of its two lines even when
# lines at the frame edge are missed. The sequence is not a palindrome, so a
# camera rotated 180 degrees reads it backwards and the orientation is known
# too. Crossings will saturate towards white in the photo; the identification
# uses the runs between crossings.
#
# The APA-106 fitted until 2026-09-09 had RED and GREEN SWAPPED, and the plot
# file compensated for it (SWAP_RG). The SK6812 RGBW that replaced it is wired
# straight, so the flag is off — but it stays here because the next part change
# is the one that needs it. The reference image shows what the camera sees.
#
# Reference image convention matches undistort.py rectify: PPM px/mm, MARGIN mm
# of black beyond the bed on every side, +x right, +y up (row 0 is the top).

import argparse
import os

from PIL import Image, ImageDraw
import outdirs as OD

BED = (393.0, 262.0)          # mm
SWAP_RG = False                # the SK6812 RGBW is straight; the old APA-106 was not
# Hue sequence (what the camera sees). Six well-separated colours; the
# secondaries use two channels each. Full range: exposure is set at plot time
# with plotter.pl's `brightness N`, so the pattern needn't change with the LED.
HUES = [
    ('red',     (255, 0, 0)),
    ('green',   (0, 255, 0)),
    ('blue',    (0, 0, 255)),
    ('yellow',  (255, 255, 0)),
    ('magenta', (255, 0, 255)),
    ('cyan',    (0, 255, 255)),
]

# Grid: verticals every 25 mm, horizontals every 20 mm, the full bed less a
# small inset so no stroke runs into a limit.
X0, X1, XSTEP = 13.0, 388.0, 25.0     # 16 verticals
Y0, Y1, YSTEP = 2.0, 262.0, 20.0      # 14 horizontals

PPM = 8.0
MARGIN = 5.0


def frange(a, b, step):
    out, v = [], a
    while v <= b + 1e-9:
        out.append(round(v, 3))
        v += step
    return out


def lines():
    """(name, colour_index, (x0, y0), (x1, y1)) in draw order, serpentine so
    the air moves stay short. Horizontals first, bottom to top, then verticals
    left to right. Colour index runs continuously through the whole sequence."""
    out, k = [], 0
    for i, y in enumerate(frange(Y0, Y1, YSTEP)):
        a, b = (X0, X1) if i % 2 == 0 else (X1, X0)
        out.append((f"h{i} y={y:g}", k % len(HUES), (a, y), (b, y)))
        k += 1
    for j, x in enumerate(frange(X0, X1, XSTEP)):
        a, b = (Y1, Y0) if j % 2 == 0 else (Y0, Y1)   # first one starts where the last h ended
        out.append((f"v{j} x={x:g}", k % len(HUES), (x, a), (x, b)))
        k += 1
    return out


def write_plot(path):
    L = lines()
    with open(path, 'w') as f:
        f.write("# Colour-coded calibration grid — generated by cal_colour.py, do not edit.\n")
        f.write(f"# {len(frange(Y0, Y1, YSTEP))} horizontals {YSTEP:g} mm apart, "
                f"{len(frange(X0, X1, XSTEP))} verticals {XSTEP:g} mm apart.\n")
        f.write("# Colours are full range: set the exposure with `brightness N` first.\n")
        f.write("# Hue sequence (as SEEN): " + " ".join(n for n, _ in HUES) + ", repeating.\n")
        f.write("# Reference image: cal_colour_ref.png. Both axes in ONE frame.\n\n")
        f.write("home\nstatus          # check WPos:393.000,0.000 before plotting\n\n")
        f.write("lightpen on\nled on\n\n")
        last = None
        for name, ci, p0, p1 in L:
            hue, (r, g, b) = HUES[ci]
            emit = (g, r, b) if SWAP_RG else (r, g, b)
            f.write(f"# {name} {hue}\n")
            if emit != last:
                f.write(f"colour {emit[0]} {emit[1]} {emit[2]}\n")
                last = emit
            f.write(f"moveto {p0[0]:g} {p0[1]:g}\n")
            f.write(f"drawto {p1[0]:g} {p1[1]:g}\n")
        f.write("\npenup\ncolour off\nhome            # park at the home corner when done\n")
    print(f"wrote {path}: {len(L)} strokes")


def write_ref(path):
    W = int(round((BED[0] + 2 * MARGIN) * PPM))
    H = int(round((BED[1] + 2 * MARGIN) * PPM))
    im = Image.new('RGB', (W, H), (0, 0, 0))
    d = ImageDraw.Draw(im)

    def px(p):
        return ((p[0] + MARGIN) * PPM, (BED[1] + MARGIN - p[1]) * PPM)

    # Bed outline, dim grey — a guide for the eye, not part of the plot.
    d.rectangle([px((0, BED[1])), px((BED[0], 0))], outline=(40, 40, 40), width=1)
    for name, ci, p0, p1 in lines():
        d.line([px(p0), px(p1)], fill=HUES[ci][1], width=3)
    im.save(path)
    print(f"wrote {path}: {W}x{H} px, {PPM:g} px/mm, {MARGIN:g} mm margin")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--plot', default=OD.plot('cal_colour.plot'))
    ap.add_argument('--ref', default=OD.preview('cal_colour_ref.png'))
    a = ap.parse_args()
    write_plot(a.plot)
    write_ref(a.ref)


if __name__ == '__main__':
    main()
