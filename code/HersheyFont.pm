package HersheyFont;
#
# HersheyFont.pm — Render text using Hershey vector fonts
# for the Tektronix 4662 plotter.
#
# Single-stroke vector fonts, public domain (Dr. A. V. Hershey, 1967).
# Glyph data parsed from Paul Bourke-style C array .txt files at load time.
#
# Available fonts (font => filename, col_width):
#   simplex  => simplex.txt  (112 cols)  — roman single-stroke (default)
#   scriptc  => scriptc.txt  (140 cols)  — script complex (cursive)
#   scripts  => scripts.txt  (140 cols)  — script simplex (cursive, simpler)
#
# Returns moveto/drawto command lists in the same format as PlotterSVG.
#

use strict;
use warnings;
use Exporter 'import';
use File::Basename;
use JSON::PP;

our @EXPORT_OK = qw(render_text load_font);

# Font registry: name => { file => filename, ... }
# txt fonts: col_width required, scale_ref = cap height in font units (default 21)
# json fonts: type => 'json', generated by ttf_to_font.py
my %FONT_INFO = (
  simplex => { file => 'simplex.txt', col_width => 112 },
  scriptc => { file => 'scriptc.txt', col_width => 140 },
  scripts => { file => 'scripts.txt', col_width => 140 },
  qerufus => { file => 'qerufus.json', type => 'json' },
);

my %FONT_CACHE;  # font_name => \%glyphs

sub _load_font {
  my ($font_name) = @_;
  return $FONT_CACHE{$font_name} if exists $FONT_CACHE{$font_name};

  my $dir = dirname(__FILE__);

  # Look up in registry, or auto-discover a .json file.
  my $info = $FONT_INFO{$font_name};
  if (!$info) {
    my $json_file = "$dir/$font_name.json";
    if (-f $json_file) {
      $info = { file => "$font_name.json", type => 'json' };
    } else {
      die "HersheyFont: unknown font '$font_name' " .
          "(known: " . join(', ', sort keys %FONT_INFO) . "; " .
          "or convert a TTF with ttf_to_font.py)\n";
    }
  }

  my $file      = "$dir/$info->{file}";
  my $col_width = $info->{col_width};

  open(my $fh, '<', $file) or die "HersheyFont: cannot open $file: $!\n";
  my $content = do { local $/; <$fh> };
  close($fh);

  my %glyphs;

  if (($info->{type} // '') eq 'json') {
    my $data = decode_json($content);
    $glyphs{_scale_ref} = $data->{ascender};
    for my $code (32 .. 126) {
      my $g = $data->{glyphs}{$code};
      next unless defined $g;
      my @vertices;
      for my $contour (@{$g->{contours}}) {
        push @vertices, undef if @vertices;  # pen up between contours
        for my $pt (@$contour) {
          push @vertices, [$pt->[0], $pt->[1]];
        }
      }
      $glyphs{chr($code)} = { width => $g->{advance}, vertices => \@vertices };
    }
  } else {
    # Paul Bourke-style C array format.
    $content =~ s/.*?\{//s;
    $content =~ s/\}.*//s;
    $content =~ s|/\*.*?\*/||gs;
    my @nums = ($content =~ /(-?\d+)/g);

    for my $i (0 .. 94) {
      my $base         = $i * $col_width;
      my $vertex_count = $nums[$base];
      my $width        = $nums[$base + 1];
      my @vertices;
      for my $j (0 .. $vertex_count - 1) {
        my $x = $nums[$base + 2 + $j * 2];
        my $y = $nums[$base + 2 + $j * 2 + 1];
        if ($x == -1 && $y == -1) {
          push @vertices, undef;
        } else {
          push @vertices, [$x, $y];
        }
      }
      $glyphs{chr(32 + $i)} = { width => $width, vertices => \@vertices };
    }
  }

  $FONT_CACHE{$font_name} = \%glyphs;
  return \%glyphs;
}

# Load default font at module load time.
_load_font('simplex');

# ---- Public API -------------------------------------------------------------

sub load_font {
  my ($font_name) = @_;
  _load_font($font_name);
}

sub render_text {
  my ($text, %opts) = @_;
  my $x         = $opts{x}      // 0;
  my $y         = $opts{y}      // 0;
  my $height    = $opts{height} // 10;
  my $font_name = $opts{font}   // 'simplex';

  my $glyphs    = _load_font($font_name);
  my $scale_ref = $glyphs->{_scale_ref} // 21;
  my $scale     = $height / $scale_ref;

  my @cmds;
  my $cursor_x = $x;

  for my $ch (split //, $text) {
    my $glyph = $glyphs->{$ch};
    unless (defined $glyph) {
      # Unknown character: advance by space width.
      $cursor_x += ($glyphs->{' '}{width} // 16) * $scale;
      next;
    }

    my $pen_up = 1;
    for my $v (@{$glyph->{vertices}}) {
      if (!defined $v) {
        $pen_up = 1;
        next;
      }
      my $px = $cursor_x + $v->[0] * $scale;
      my $py = $y + $v->[1] * $scale;
      if ($pen_up) {
        push @cmds, { cmd => 'moveto', x => $px, y => $py };
        $pen_up = 0;
      } else {
        push @cmds, { cmd => 'drawto', x => $px, y => $py };
      }
    }

    $cursor_x += $glyph->{width} * $scale;
  }

  return \@cmds;
}

1;
