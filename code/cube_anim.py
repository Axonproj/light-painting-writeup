#!/usr/bin/env python3
#
# cube_anim.py — an animation: a blue wireframe cube turning once (360
# degrees) about the vertical, seen close up in strong perspective. Writes
# cube_anim_preview.gif, and with --plots one plot file per frame.
#
# The cube's edge is 2 (centre at the origin). It is tipped --tilt degrees
# towards the camera so its top face shows, and the camera sits --camera
# from the centre: at the default 3.2 the near corner is about twice as far
# from the vanishing of the far one, so the near edges look much longer than
# the far ones. One scale for all frames, set by the largest, so the cube
# does not breathe; the frames' widest view sets the bed fit.
#
# --plots DIR also writes one plot file per frame, DIR/cube_NNN.plot: blue,
# dynamic brightness at --speed, the 12 edges as 4 strokes (top square and
# down to the bottom square in one, then the three other pillars). The frame
# files do not home: a series is shot in one homing (homing repeats only to
# ~1.2 mm, which would shake the cube from frame to frame), after a `home`
# and a check of WPos 393,0.
#
# The preview draws as the light pen does: 8 mm line, overlaps add up,
# a halo of --glow mm.
#
#   ./cube_anim.py --frames 72 --fps 24

import argparse
import math

import numpy as np
from PIL import Image, ImageDraw, ImageFilter
import outdirs as OD

BED = (393.0, 262.0)
MARGIN_MM = 15.0
LINE = 8.0                # mm, the LED's line
PX = 2.0                  # preview px per mm
BLUE = (40, 110, 255)

VERTS = [(x, y, z) for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)]
EDGES = [(i, j) for i in range(8) for j in range(i + 1, 8)
         if sum(a != b for a, b in zip(VERTS[i], VERTS[j])) == 1]


def project(a, az):
    """The 8 corners, turned az about the vertical, tipped, in perspective."""
    th = math.radians(a.tilt)
    out = []
    for x, y, z in VERTS:
        c, s = math.cos(az), math.sin(az)
        x, z = c * x + s * z, -s * x + c * z               # turn about the vertical
        c, s = math.cos(th), math.sin(th)
        y, z = c * y - s * z, s * y + c * z                # tip the top towards the camera
        f = a.camera / (a.camera - z)
        out.append((x * f, y * f))
    return out


# Corner index: x*4 + y*2 + z (VERTS order). Top square y=1, bottom y=-1.
TOP = [2, 3, 7, 6]
BOT = [0, 1, 5, 4]
ACCEL = 800.0             # mm/s^2, GRBL's


def strokes():
    """The 12 edges as 4 strokes: top round, down a pillar, bottom round, 3 pillars."""
    first = TOP + [TOP[0]] + BOT + [BOT[0]]
    return [first, [BOT[1], TOP[1]], [TOP[2], BOT[2]], [BOT[3], TOP[3]]]


def stroke_secs(pts, v):
    """Drawing time, stopping at every corner (a trapezoid per edge)."""
    t = 0.0
    for p, q in zip(pts, pts[1:]):
        L = math.dist(p, q)
        if L > v * v / ACCEL:
            t += L / v + v / ACCEL
        else:
            t += 2 * math.sqrt(L / ACCEL)
    return t


def write_plots(a, frames, fit):
    import os
    os.makedirs(a.plots, exist_ok=True)
    v = a.speed / 60.0
    worst = (0, 0.0)
    for j, pts in enumerate(frames):
        mm = [fit(p) for p in pts]
        for x, y in mm:                                    # never near the switches or off the bed
            assert 5 <= x <= 385 and 5 <= y <= 257, (j, x, y)
        secs = sum(stroke_secs([mm[k] for k in st], v) for st in strokes())
        worst = max(worst, (secs, j))
        L = ["# cube_%03d.plot — generated by cube_anim.py, do not edit." % j,
             "# Frame %d of %d: a wireframe cube turned %.1f degrees about the vertical," % (j, a.frames, 360.0 * j / a.frames),
             "# tipped %g degrees, eye at %g half-edges. Shot as a series in ONE homing:" % (a.tilt, a.camera),
             "# no home here; `home` and check WPos:393.000,0.000 before the first frame.",
             "# Dynamic brightness on. UNPLUG THE SOLENOID (see `help`).",
             "# Estimated drawing %.1f s." % secs, "",
             "lightpen on", "speed %d" % a.speed, "dynamic on", "colour %s" % a.colour, ""]
        for st in strokes():
            x, y = mm[st[0]]
            L.append("moveto %.2f %.2f" % (x, y))
            L += ["drawto %.2f %.2f" % mm[k] for k in st[1:]]
        L += ["", "dynamic off", "penup", "colour off", "moveto 380 20     # park near home, no re-homing", ""]
        open(os.path.join(a.plots, "cube_%03d.plot" % j), "w").write("\n".join(L))
    print("%s: %d plot files, longest drawing %.1f s (frame %d)" % (a.plots, len(frames), worst[0], worst[1]))


def main():
    ap = argparse.ArgumentParser(description="A blue wireframe cube turning once, in strong perspective.")
    ap.add_argument("--camera", type=float, default=3.2, help="eye distance from the centre, half-edges")
    ap.add_argument("--tilt", type=float, default=25.0, help="degrees the top is tipped towards the camera")
    ap.add_argument("--frames", type=int, default=72)
    ap.add_argument("--fps", type=float, default=24.0)
    ap.add_argument("--glow", type=float, default=2.0, help="preview halo, mm")
    ap.add_argument("--out", default=OD.preview("cube_anim_preview.gif"))
    ap.add_argument("--plots", help="also write DIR/cube_NNN.plot, one per frame")
    ap.add_argument("--speed", type=int, default=6000, help="plot files' feed, mm/min")
    ap.add_argument("--colour", default="0 0 255")
    a = ap.parse_args()

    frames = [project(a, 2 * math.pi * j / a.frames) for j in range(a.frames)]
    xs = [p[0] for f in frames for p in f]
    ys = [p[1] for f in frames for p in f]
    s = min((BED[0] - 2 * MARGIN_MM) / (max(xs) - min(xs)), (BED[1] - 2 * MARGIN_MM) / (max(ys) - min(ys)))
    ox = BED[0] / 2 - s * (max(xs) + min(xs)) / 2
    oy = BED[1] / 2 - s * (max(ys) + min(ys)) / 2

    if a.plots:
        write_plots(a, frames, lambda q: (ox + s * q[0], oy + s * q[1]))

    W, H = int(BED[0] * PX), int(BED[1] * PX)
    P = lambda q: ((ox + s * q[0]) * PX, (BED[1] - (oy + s * q[1])) * PX)
    width = max(1, int(LINE * PX * 0.8))
    images = []
    for pts in frames:
        acc = np.zeros((H, W, 3), np.float32)
        for i, j in EDGES:                                 # edges add up where they cross, as light does
            layer = Image.new("RGB", (W, H))
            dr = ImageDraw.Draw(layer)
            p, q = P(pts[i]), P(pts[j])
            dr.line([p, q], fill=BLUE, width=width)
            for x, y in (p, q):
                dr.ellipse([x - width / 2, y - width / 2, x + width / 2, y + width / 2], fill=BLUE)
            acc += np.asarray(layer, np.float32)
        img = Image.fromarray(np.clip(acc, 0, 255).astype(np.uint8))
        if a.glow:
            halo = np.asarray(img.filter(ImageFilter.GaussianBlur(a.glow * PX * 2)), np.float32)
            img = Image.fromarray(np.clip(np.asarray(img, np.float32) + 0.8 * halo, 0, 255).astype(np.uint8))
        images.append(img)
    images[0].save(a.out, save_all=True, append_images=images[1:],
                   duration=round(1000 / a.fps), loop=0, optimize=False)
    print("%s: %d frames at %g fps, %.1f s, one turn" % (a.out, a.frames, a.fps, a.frames / a.fps))


main()
